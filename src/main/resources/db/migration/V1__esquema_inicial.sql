-- =====================================================================
-- V1 · Esquema inicial de Sillón (PostgreSQL)
-- Generado por Hibernate a partir de las entidades y revisado a mano:
--   * nombres legibles para llaves foráneas, únicas y checks
--   * índices para las consultas frecuentes (PostgreSQL NO indexa las FK solo)
--   * checks de negocio como segunda barrera
-- Regla: este archivo NUNCA se edita después de aplicado. Todo cambio va en V2, V3...
-- Ojo: los checks de enums (estado, origen, plan, rol, motivo) deben actualizarse
-- con una migración si se agrega un valor nuevo al enum en Java.
-- =====================================================================

create table salones (
    id                    bigint generated by default as identity,
    nombre                varchar(100) not null,
    slug                  varchar(120) not null,
    ciudad                varchar(60)  not null,
    direccion             varchar(150) not null,
    telefono              varchar(30)  not null,
    plan                  varchar(20)  not null,
    creditos_ia           integer      not null,
    stripe_suscripcion_id varchar(100),
    hora_apertura         time(0)      not null,
    hora_cierre           time(0)      not null,
    intervalo_minutos     integer      not null,
    abre_domingos         boolean      not null,
    fecha_creacion        timestamp(6) not null,
    constraint pk_salones primary key (id),
    constraint uk_salones_slug unique (slug),
    constraint ck_salones_plan check (plan in ('GRATIS', 'PRO')),
    constraint ck_salones_creditos_no_negativos check (creditos_ia >= 0),
    constraint ck_salones_horario check (hora_apertura < hora_cierre),
    constraint ck_salones_intervalo check (intervalo_minutos > 0)
);

create table usuarios (
    id       bigint generated by default as identity,
    salon_id bigint       not null,
    nombre   varchar(100) not null,
    email    varchar(150) not null,
    password varchar(255) not null,
    rol      varchar(20)  not null,
    activo   boolean      not null,
    constraint pk_usuarios primary key (id),
    constraint uk_usuarios_email unique (email),
    constraint ck_usuarios_rol check (rol in ('DUENO', 'ESTILISTA', 'ADMIN')),
    constraint fk_usuarios_salon foreign key (salon_id) references salones (id)
);

create table servicios (
    id               bigint generated by default as identity,
    salon_id         bigint       not null,
    nombre           varchar(80)  not null,
    descripcion      varchar(300),
    duracion_minutos integer      not null,
    precio           integer      not null,
    activo           boolean      not null,
    constraint pk_servicios primary key (id),
    constraint ck_servicios_duracion check (duracion_minutos between 15 and 480),
    constraint ck_servicios_precio_positivo check (precio > 0),
    constraint fk_servicios_salon foreign key (salon_id) references salones (id)
);

create table estilista_servicios (
    estilista_id bigint not null,
    servicio_id  bigint not null,
    constraint pk_estilista_servicios primary key (estilista_id, servicio_id),
    constraint fk_estilista_servicios_estilista foreign key (estilista_id) references usuarios (id),
    constraint fk_estilista_servicios_servicio foreign key (servicio_id) references servicios (id)
);

create table clientes (
    id       bigint generated by default as identity,
    salon_id bigint       not null,
    nombre   varchar(100) not null,
    telefono varchar(30)  not null,
    constraint pk_clientes primary key (id),
    -- Mismo nombre que en @UniqueConstraint de la entidad Cliente
    constraint uk_cliente_salon_telefono unique (salon_id, telefono),
    constraint fk_clientes_salon foreign key (salon_id) references salones (id)
);

create table citas (
    id                  bigint generated by default as identity,
    salon_id            bigint       not null,
    cliente_id          bigint       not null,
    estilista_id        bigint       not null,
    servicio_id         bigint       not null,
    inicio              timestamp(6) not null,
    fin                 timestamp(6) not null,
    precio              integer      not null,
    estado              varchar(20)  not null,
    origen              varchar(20)  not null,
    nota                varchar(300),
    fecha_creacion      timestamp(6) not null,
    fecha_actualizacion timestamp(6) not null,
    constraint pk_citas primary key (id),
    constraint ck_citas_estado check (estado in ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA', 'NO_ASISTIO')),
    constraint ck_citas_origen check (origen in ('SALON', 'EN_LINEA')),
    constraint ck_citas_fin_despues_de_inicio check (fin > inicio),
    constraint ck_citas_precio_no_negativo check (precio >= 0),
    constraint fk_citas_salon foreign key (salon_id) references salones (id),
    constraint fk_citas_cliente foreign key (cliente_id) references clientes (id),
    constraint fk_citas_estilista foreign key (estilista_id) references usuarios (id),
    constraint fk_citas_servicio foreign key (servicio_id) references servicios (id)
);

create table solicitudes_contacto (
    id               bigint generated by default as identity,
    salon_id         bigint        not null,
    cliente_nombre   varchar(100)  not null,
    cliente_contacto varchar(120)  not null,
    mensajes         varchar(2000) not null,
    motivo           varchar(30)   not null,
    estado           varchar(20)   not null,
    fecha_creacion   timestamp(6)  not null,
    constraint pk_solicitudes_contacto primary key (id),
    constraint ck_solicitudes_motivo check (motivo in ('PEDIDO_POR_IA', 'REGLA_DE_SEGURIDAD')),
    constraint ck_solicitudes_estado check (estado in ('PENDIENTE', 'ATENDIDA')),
    constraint fk_solicitudes_salon foreign key (salon_id) references salones (id)
);

create table eventos_stripe (
    id              varchar(100) not null,
    tipo            varchar(100) not null,
    fecha_procesado timestamp(6) not null,
    constraint pk_eventos_stripe primary key (id)
);

create table sesiones_refresco (
    id              bigint generated by default as identity,
    usuario_id      bigint                      not null,
    hash            varchar(64)                 not null,
    familia         varchar(36)                 not null,
    creado_en       timestamp(6) with time zone not null,
    expira_en       timestamp(6) with time zone not null,
    expira_absoluto timestamp(6) with time zone not null,
    usado_en        timestamp(6) with time zone,
    revocado_en     timestamp(6) with time zone,
    constraint pk_sesiones_refresco primary key (id),
    constraint uk_sesiones_refresco_hash unique (hash),
    constraint fk_sesiones_refresco_usuario foreign key (usuario_id) references usuarios (id)
);

