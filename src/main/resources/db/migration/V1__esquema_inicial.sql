create index idx_usuarios_salon_rol on usuarios (salon_id, rol);
create index idx_estilista_servicios_servicio on estilista_servicios (servicio_id);

-- Bandeja de solicitudes del chatbot (más recientes primero)
create index idx_solicitudes_salon_fecha on solicitudes_contacto (salon_id, fecha_creacion desc);

